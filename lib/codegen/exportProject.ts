import archiver from "archiver";
import fs from "node:fs";
import path from "node:path";
import type { PageSpec, WebsiteSpec } from "@/lib/types";

const ROOT = process.cwd();

function readSource(relPath: string): string {
  return fs.readFileSync(path.join(ROOT, relPath), "utf-8");
}

function slugifyPackageName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || "ai-generated-site";
}

function packageJson(spec: WebsiteSpec): string {
  return JSON.stringify(
    {
      name: slugifyPackageName(spec.meta.siteName),
      version: "0.1.0",
      private: true,
      scripts: { dev: "next dev", build: "next build", start: "next start" },
      dependencies: {
        next: "15.1.0",
        react: "18.3.1",
        "react-dom": "18.3.1",
      },
      devDependencies: {
        "@types/node": "22.10.2",
        "@types/react": "18.3.18",
        "@types/react-dom": "18.3.5",
        autoprefixer: "10.4.20",
        postcss: "8.4.49",
        tailwindcss: "3.4.17",
        typescript: "5.7.2",
      },
    },
    null,
    2
  );
}

