export async function buildExportZip(spec: WebsiteSpec): Promise<Buffer> {
  const archive = archiver("zip", { zlib: { level: 9 } });
  const chunks: Buffer[] = [];
  archive.on("data", (chunk: Buffer) => chunks.push(chunk));
  const done = new Promise<void>((resolve, reject) => {
    archive.on("end", () => resolve());
    archive.on("error", reject);
  });

  const componentFiles = fs.readdirSync(path.join(ROOT, "lib/components")).filter((f) => f.endsWith(".tsx"));
  for (const file of componentFiles) {
    archive.append(readSource(`lib/components/${file}`), { name: `lib/components/${file}` });
  }
  archive.append(readSource("lib/types.ts"), { name: "lib/types.ts" });
  archive.append(readSource("app/globals.css"), { name: "app/globals.css" });
  archive.append(readSource("tailwind.config.ts"), { name: "tailwind.config.ts" });
  archive.append(readSource("postcss.config.js"), { name: "postcss.config.js" });

  archive.append(packageJson(spec), { name: "package.json" });
  archive.append(tsconfigJson(), { name: "tsconfig.json" });
  archive.append(nextConfigJs(), { name: "next.config.js" });
  archive.append(dataSiteTs(spec), { name: "data/site.ts" });
  archive.append(rootLayoutTsx(spec), { name: "app/layout.tsx" });
  archive.append(sitemapTs(), { name: "app/sitemap.ts" });
  archive.append(robotsTs(), { name: "app/robots.ts" });
  archive.append(readmeMd(spec), { name: "README.md" });
  archive.append("node_modules\n.next\n.env*\n", { name: ".gitignore" });

  for (const page of spec.pages) {
    const filePath = page.slug === "home" ? "app/page.tsx" : `app/${page.slug}/page.tsx`;
    archive.append(pageTsx(page), { name: filePath });
  }

  // Copy any uploaded assets referenced by this project so the export is self-contained.
  const uploadsDir = path.join(ROOT, "public", "uploads");
  if (fs.existsSync(uploadsDir)) {
    for (const asset of spec.assets) {
      const assetPath = path.join(ROOT, "public", asset.url.replace(/^\//, ""));
      if (fs.existsSync(assetPath)) {
        archive.append(fs.createReadStream(assetPath), { name: `public${asset.url}` });
      }
    }
  }

  await archive.finalize();
  await done;
  return Buffer.concat(chunks);
}
